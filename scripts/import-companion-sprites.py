"""Losslessly embed used animal frames. Requires Pillow for this developer-only importer.

Download the original packs from the sources in THIRD_PARTY_NOTICES.md, then run:
  python scripts/import-companion-sprites.py --cat '/path/Cat Sprite Sheet.png' \
    --fox '/path/Fox Sprite Sheet.png' --frog-dir '/path/ToxicFrogGreenBrown'
Only used frames are embedded; source packs are not distributed with Pagebot.
"""
import argparse
import hashlib
import json
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ALPHABET = '0123456789abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ'
START = '// BEGIN SOURCED COMPANION FRAMES (generated by scripts/import-companion-sprites.py)'
END = '// END SOURCED COMPANION FRAMES'


def build(kind, artist, url, files, crop, clips, states):
    palette = {}
    art = {'source': {'artist': artist, 'url': url}, 'palette': {}, 'frames': [], 'clips': {}, 'states': states}
    manifest = {'source': {'artist': artist, 'url': url, 'crop': [*crop, 26, 26], 'files': []}, 'states': states, 'clips': {}}
    images = {}
    for key, (path, name, cell) in files.items():
        images[key] = Image.open(path).convert('RGBA')
        manifest['source']['files'].append({'name': name, 'sha256': hashlib.sha256(path.read_bytes()).hexdigest()})
    for clip, (file, row, count, duration) in clips.items():
        path, name, cell = files[file]
        im = images[file]
        ids, expected = [], []
        durations = duration if isinstance(duration, list) else [duration] * count
        for col in range(count):
            tile = im.crop((col * cell, row * cell, (col + 1) * cell, (row + 1) * cell))
            pixels = tile.crop((crop[0], crop[1], crop[0] + 26, crop[1] + 26))
            # Refuse a crop that loses any visible source pixel.
            assert sum(tile.tobytes()[3::4]) == sum(pixels.tobytes()[3::4]), (kind, clip, col, 'clipped')
            rgba = bytearray(pixels.tobytes())
            for offset in range(0, len(rgba), 4):
                if not rgba[offset + 3]:
                    rgba[offset:offset + 4] = bytes(4)
            normalized = Image.frombytes('RGBA', pixels.size, bytes(rgba))
            bbox = normalized.getbbox()
            assert bbox and bbox[0] > 0 and bbox[1] > 0 and bbox[2] < 26 and bbox[3] < 26, (kind, clip, col, bbox)
            x, y, right, bottom = bbox
            rows = []
            for py in range(y, bottom):
                text = ''
                for px in range(x, right):
                    color = normalized.getpixel((px, py))
                    if not color[3]:
                        text += '.'
                    else:
                        if color not in palette:
                            letter = ALPHABET[len(palette)]
                            palette[color] = letter
                            art['palette'][letter] = '#' + ''.join(f'{v:02x}' for v in (color[:3] if color[3] == 255 else color))
                        text += palette[color]
                rows.append(text)
            index = len(art['frames'])
            art['frames'].append({'x': x, 'y': y, 'rows': rows})
            ids.append(index)
            expected.append({'index': index, 'sha256': hashlib.sha256(normalized.tobytes()).hexdigest(), 'source': name, 'rect': [col * cell, row * cell, cell, cell]})
        art['clips'][clip] = {'frames': ids, 'durations': durations}
        manifest['clips'][clip] = {'frames': expected, 'durations': durations}
    if kind == 'frog':
        # The artist supplied no sleep clip: use an unaltered closed-eye idle frame.
        art['clips']['quiet'] = {'frames': [art['clips']['idle']['frames'][2]], 'durations': [100]}
        manifest['clips']['quiet'] = {'frames': [manifest['clips']['idle']['frames'][2]], 'durations': [100]}
    return art, manifest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--cat', type=Path, required=True)
    parser.add_argument('--fox', type=Path, required=True)
    parser.add_argument('--frog-dir', type=Path, required=True)
    args = parser.parse_args()
    art, manifest = {}, {}
    animal_specs = {
        'cat': ('Elthen', 'https://elthen.itch.io/2d-pixel-art-cat-sprites', {'sheet': (args.cat, 'Cat Sprite Sheet.png', 32)}, (3, 9),
            {'idle': ('sheet', 0, 4, 120), 'look': ('sheet', 1, 4, 120), 'groom': ('sheet', 2, 4, 120), 'walk': ('sheet', 4, 8, 120), 'sleep': ('sheet', 6, 4, 120), 'paw': ('sheet', 7, 6, 120), 'jump': ('sheet', 8, 7, 120), 'scared': ('sheet', 9, 8, 120)},
            {'idle': 'idle', 'working': 'groom', 'nap': 'sleep', 'locked': 'sleep', 'hop': 'jump', 'happy': 'paw', 'shrug': 'scared', 'wave': 'paw', 'wake': 'look'}),
        'fox': ('Elthen', 'https://elthen.itch.io/2d-pixel-art-fox-sprites', {'sheet': (args.fox, 'Fox Sprite Sheet.png', 32)}, (3, 9),
            {'idle': ('sheet', 0, 5, 120), 'look': ('sheet', 1, 14, 120), 'walk': ('sheet', 2, 8, 120), 'catch': ('sheet', 3, 11, 120), 'flinch': ('sheet', 4, 5, 120), 'sleep': ('sheet', 5, 6, 120)},
            {'idle': 'idle', 'working': 'look', 'nap': 'sleep', 'locked': 'sleep', 'hop': 'catch', 'happy': 'look', 'shrug': 'flinch', 'wave': 'look', 'wake': 'look'}),
        'frog': ('Eduardo Scarpato', 'https://eduardscarpato.itch.io/toxic-frog-animations-pixel-art-2d-free',
            {k: (args.frog_dir / f'ToxicFrogGreenBrown_{k.title()}.png', f'ToxicFrogGreenBrown_{k.title()}.png', 48) for k in ['idle', 'hop', 'hurt']}, (8, 9),
            {'idle': ('idle', 0, 8, 100), 'hop': ('hop', 0, 7, 100), 'hurt': ('hurt', 0, 4, [500, 100, 100, 100])},
            {'idle': 'idle', 'working': 'idle', 'nap': 'quiet', 'locked': 'quiet', 'hop': 'hop', 'happy': 'hop', 'shrug': 'hurt', 'wave': 'idle', 'wake': 'idle'}),
    }
    for kind, spec in animal_specs.items():
        art[kind], manifest[kind] = build(kind, *spec)
    widget = ROOT / 'public/widget.html'
    text = widget.read_text()
    embedded = START + '\nconst COMPANION_ART = ' + json.dumps(art, separators=(',', ':')) + ';\n' + END
    if START in text:
        begin = text.index(START)
        end = text.index(END, begin) + len(END)
        text = text[:begin] + embedded + text[end:]
    else:
        text = text.replace('const COMPANIONS = ', embedded + '\nconst COMPANIONS = ', 1)
    widget.write_text(text)
    (ROOT / 'tests/fixtures/companion-art.json').write_text(json.dumps(manifest, indent=2) + '\n')
    print('Embedded source frames:', {kind: len(data['frames']) for kind, data in art.items()})

if __name__ == '__main__':
    main()
